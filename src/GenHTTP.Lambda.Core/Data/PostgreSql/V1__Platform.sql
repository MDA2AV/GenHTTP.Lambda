-- The platform's records, in PostgreSQL: the schema platform.
--
-- The schema as it stands after the migrations of SQLite (Data/Migrations),
-- written once in PostgreSQL's types, since an installation starts on
-- PostgreSQL with none of their history: ids are identities, flags booleans,
-- times timestamps with their zone, and bytes bytea. Names, keys, indexes and
-- defaults are SQLite's, so the model maps both alike. From here on, every
-- change to the schema is a migration in both sets, each numbered on its own.

CREATE TABLE lambdas
(
    id                   bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_key           text        NOT NULL,
    private_key          text        NOT NULL,
    tier                 text        NOT NULL,
    tier_changed         timestamptz NULL,
    active_version       integer     NULL,
    created              timestamptz NOT NULL,
    modified             timestamptz NOT NULL,
    deployed             timestamptz NULL,
    last_seen            timestamptz NULL,
    analytics_since      timestamptz NULL,
    domain               text        NULL,
    editor_view          text        NOT NULL DEFAULT 'Full',
    secret_salt          bytea       NULL,
    blocked              timestamptz NULL,
    block_reason         text        NULL,
    connectivity         text        NULL,
    connectivity_changed timestamptz NULL,
    connectivity_purpose text        NULL,
    connectivity_note    text        NULL
);

CREATE UNIQUE INDEX ux_lambdas_public_key ON lambdas (public_key);
CREATE UNIQUE INDEX ux_lambdas_private_key ON lambdas (private_key);
CREATE UNIQUE INDEX ux_lambdas_domain ON lambdas (domain) WHERE domain IS NOT NULL;
CREATE INDEX ix_lambdas_modified ON lambdas (modified);
CREATE INDEX ix_lambdas_last_seen ON lambdas (last_seen);

CREATE TABLE deployments
(
    id            bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lambda_id     bigint      NOT NULL REFERENCES lambdas (id) ON DELETE CASCADE,
    version       integer     NOT NULL,
    created       timestamptz NOT NULL,
    specification text        NULL,
    change        text        NULL,
    origin        text        NULL
);

CREATE UNIQUE INDEX ux_deployments_lambda_version ON deployments (lambda_id, version);

CREATE TABLE events
(
    id         bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind       text        NOT NULL,
    lambda_id  bigint      NULL,
    public_key text        NULL,
    occurred   timestamptz NOT NULL
);

CREATE INDEX ix_events_occurred ON events (occurred);
CREATE INDEX ix_events_kind_occurred ON events (kind, occurred);

CREATE TABLE activations
(
    id        bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lambda_id bigint      NOT NULL REFERENCES lambdas (id) ON DELETE CASCADE,
    version   integer     NOT NULL,
    started   timestamptz NOT NULL,
    origin    text        NULL,
    ended     timestamptz NULL,
    ended_by  text        NULL
);

CREATE INDEX ix_activations_lambda_started ON activations (lambda_id, started);

CREATE TABLE showcases
(
    lambda_id   bigint      NOT NULL PRIMARY KEY REFERENCES lambdas (id) ON DELETE CASCADE,
    title       text        NOT NULL,
    description text        NOT NULL,
    image       bytea       NOT NULL,
    image_type  text        NOT NULL,
    created     timestamptz NOT NULL,
    updated     timestamptz NOT NULL
);

CREATE TABLE sources
(
    lambda_id     bigint      NOT NULL PRIMARY KEY REFERENCES lambdas (id) ON DELETE CASCADE,
    published     boolean     NOT NULL,
    license       text        NOT NULL,
    author        text        NULL,
    stars         integer     NOT NULL DEFAULT 0,
    about         text        NULL,
    about_version integer     NULL,
    published_at  timestamptz NOT NULL,
    updated       timestamptz NOT NULL
);

CREATE INDEX ix_sources_published ON sources (published);

CREATE TABLE settings
(
    key   text NOT NULL PRIMARY KEY,
    value text NOT NULL
);

CREATE TABLE data_stores
(
    lambda_id bigint      NOT NULL REFERENCES lambdas (id) ON DELETE CASCADE,
    kind      text        NOT NULL,
    enabled   boolean     NOT NULL,
    changed   timestamptz NOT NULL,
    PRIMARY KEY (lambda_id, kind)
);

CREATE TABLE features
(
    id            bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lambda_id     bigint      NOT NULL REFERENCES lambdas (id) ON DELETE CASCADE,
    key           text        NOT NULL,
    name          text        NOT NULL,
    branch        text        NULL,
    specification text        NULL,
    change        text        NULL,
    base_version  integer     NOT NULL,
    origin        text        NULL,
    created       timestamptz NOT NULL,
    modified      timestamptz NOT NULL,
    preview       integer     NOT NULL DEFAULT 0,
    previewed     timestamptz NULL,
    revision      integer     NOT NULL DEFAULT 1,
    preview_of    integer     NULL
);

CREATE UNIQUE INDEX ix_features_key ON features (key);
CREATE INDEX ix_features_lambda ON features (lambda_id);
CREATE UNIQUE INDEX ix_features_branch ON features (lambda_id, branch);

CREATE TABLE secrets
(
    id         bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lambda_id  bigint      NOT NULL REFERENCES lambdas (id) ON DELETE CASCADE,
    feature_id bigint      NULL REFERENCES features (id) ON DELETE CASCADE,
    name       text        NOT NULL,
    value      bytea       NOT NULL,
    created    timestamptz NOT NULL,
    changed    timestamptz NOT NULL
);

CREATE UNIQUE INDEX ix_secrets_name ON secrets (lambda_id, COALESCE(feature_id, 0), name);
CREATE INDEX ix_secrets_feature ON secrets (feature_id) WHERE feature_id IS NOT NULL;

CREATE TABLE editor_addresses
(
    lambda_id  bigint      NOT NULL REFERENCES lambdas (id) ON DELETE CASCADE,
    address    text        NOT NULL,
    first_seen timestamptz NOT NULL,
    last_seen  timestamptz NOT NULL,
    PRIMARY KEY (lambda_id, address)
);

CREATE INDEX ix_editor_addresses_last_seen ON editor_addresses (last_seen);

CREATE TABLE address_blocks
(
    id         bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    address    text        NOT NULL UNIQUE,
    reason     text        NULL,
    public_key text        NULL,
    created    timestamptz NOT NULL
);

CREATE TABLE branding_pictures
(
    purpose text        NOT NULL PRIMARY KEY,
    type    text        NOT NULL,
    content bytea       NOT NULL,
    updated timestamptz NOT NULL
);
